#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {chromium}=require('playwright-core');
const BASE='http://127.0.0.1:8765/';
const OUT='/tmp/mohw-approved-design-shots';
fs.mkdirSync(OUT,{recursive:true});
const sizes=[{name:'phone320',width:320,height:720},{name:'phone390',width:390,height:844},{name:'tablet768',width:768,height:1024},{name:'desktop1440',width:1440,height:900}];
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_BIN||'/usr/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage']});
 try{
 for(const s of sizes){
  const page=await browser.newPage({viewport:{width:s.width,height:s.height},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const response=await page.goto(BASE,{waitUntil:'domcontentloaded',timeout:30000});
  assert.equal(response.status(),200,'site reachable');
  await page.waitForSelector('#ad-home .ad-home-tile',{timeout:12000});
  await page.waitForFunction(()=>window.MOHWGIA && document.querySelector('#guideActionDock [data-action="share"]'),null,{timeout:15000});
  assert.equal(await page.locator('#ad-home .ad-home-tile').count(),4,'four approved 3D navigation tiles');
  assert.equal(await page.locator('#ad-action-dock button').count(),4,'four unobstructed quick actions');
  assert.equal(await page.locator('#ad-home .ad-home-wrap>#ad-action-dock').count(),1,'actions are integrated beneath homepage tiles');
  assert.equal(await page.locator('#ad-action-dock').evaluate(el=>{const a=el.getBoundingClientRect();const cards=document.querySelector('.ad-home-tiles').getBoundingClientRect();return a.top>=cards.bottom-1;}),true,'actions must not cover service cards');
  assert.ok(await page.locator('#ad-header .ad-logo').isVisible(),'MOHW header visible');
  const geometry=await page.evaluate(()=>({vw:innerWidth,sw:document.documentElement.scrollWidth,bw:document.body.scrollWidth,dock:document.querySelector('#ad-action-dock')?.getBoundingClientRect().toJSON(),hero:document.querySelector('#ad-home .ad-hero')?.getBoundingClientRect().toJSON(),tile:document.querySelector('.ad-home-tile')?.getBoundingClientRect().toJSON()}));
  console.log('GEOMETRY '+s.name+' '+JSON.stringify(geometry));
  assert.ok(geometry.sw<=s.width+3 && geometry.bw<=s.width+3,'page fits phone/tablet width');
  if(s.width<=390) assert.ok(geometry.tile.width>=120,'tiles stay legible on phone');
  await page.screenshot({path:OUT+'/'+s.name+'-home.png',fullPage:true,animations:'disabled'});
  await page.locator('#ad-home [data-ad-action="video"]').click();
  await page.waitForSelector('#ad-video-dialog[open]',{timeout:4000});
  assert.equal(await page.locator('#ad-video source').getAttribute('src'),'assets/gia-introduction.mp4','real existing Gia video');
  await page.locator('[data-ad-video-close]').click();
  await page.waitForSelector('#ad-video-dialog:not([open])',{state:'hidden'});
  await page.locator('#ad-home [data-ad-nav="services"]').click();
  await page.waitForSelector('#view-services.active',{timeout:8000});
  assert.equal(await page.locator('#view-services>#ad-action-dock').count(),1,'actions appear in active map page flow');
  assert.equal(await page.locator('#ad-action-dock').evaluate(el=>{const a=el.getBoundingClientRect();const filters=document.querySelector('.ad-filters').getBoundingClientRect();return a.top>=filters.bottom-1;}),true,'action bar does not hide map filters');
  await page.waitForFunction(()=>document.querySelector('#ad-office-count')?.textContent?.includes('56'),null,{timeout:14000});
  assert.equal(await page.locator('#ad-parish option').count(),15,'all 14 parishes');
  assert.ok(await page.locator('#ad-office-list .ad-office').count()>=8,'agency listings populated');
  await page.locator('#ad-parish').selectOption('Hanover');
  assert.ok((await page.locator('#ad-office-count').textContent()).includes('4 offices'),'parish filter');
  await page.locator('#ad-search').fill('Noel Holmes');
  assert.ok((await page.locator('#ad-office-count').textContent()).includes('1 office'),'search + parish filters');
  const url=await page.locator('#ad-office-list a[href^="https://www.google.com/maps/search/"]').first().getAttribute('href');
  assert.ok(url.includes('query='),'real Google Maps address search');
  await page.locator('[data-ad-map-mode="list"]').click();
  assert.equal(await page.locator('#ad-map-panel').isHidden(),true,'list mode');
  await page.locator('[data-ad-map-mode="map"]').click();
  assert.equal(await page.locator('#ad-map-panel').isHidden(),false,'map mode');
  await page.waitForFunction(()=>!!document.querySelector('#ad-map.leaflet-container'),null,{timeout:9000});
  await page.waitForTimeout(600);
  await page.screenshot({path:OUT+'/'+s.name+'-map.png',fullPage:true,animations:'disabled'});
  await page.locator('#ad-backbar [data-ad-nav="about"]').click();
  await page.waitForSelector('#view-about.active');
  await page.locator('#ad-home [data-ad-nav="referrals"]').click();
  await page.waitForSelector('#view-referrals.active');
  assert.equal(await page.locator('#referralStepNav button').count(),6,'source-derived six steps');
  await page.screenshot({path:OUT+'/'+s.name+'-referrals.png',fullPage:true,animations:'disabled'});
  await page.locator('#ad-backbar [data-ad-nav="about"]').click();
  await page.locator('#ad-home [data-ad-nav="decision"]').click();
  await page.waitForSelector('#view-decision.active');
  await page.waitForSelector('#ad-decision-select',{timeout:7000});
  assert.ok(await page.locator('#ad-decision-select option').count()>10,'13 existing decision situations');
  await page.screenshot({path:OUT+'/'+s.name+'-decision.png',fullPage:true,animations:'disabled'});
  await page.locator('#ad-backbar [data-ad-nav="about"]').click();
  await page.locator('#ad-home [data-ad-nav="manual"]').click();
  await page.waitForSelector('#view-manual.active');
  assert.ok(await page.locator('#manual-reader').count(),'existing original manual reader retained');
  await page.screenshot({path:OUT+'/'+s.name+'-manual.png',fullPage:true,animations:'disabled'});
  await page.locator('#ad-action-dock [data-ad-action="share"]').click();
  await page.waitForSelector('#guideShareDialog[open]',{timeout:5000});
  assert.ok((await page.locator('#guideShareUrl').textContent()).startsWith(BASE),'preview QR/share link not production');
  await page.locator('#guideShareDialog [data-close]').first().click();
  assert.deepEqual(errors,[],'unexpected browser script errors');
  console.log('PASS '+s.name+': approved art, video, map, filtering, referrals, decision, manual, share');
  await page.close();
 }
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});