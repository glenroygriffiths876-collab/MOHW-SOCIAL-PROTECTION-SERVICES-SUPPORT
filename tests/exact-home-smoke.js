#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const read = p => fs.readFileSync(p, 'utf8');
const html = read('index.html');
const js = read('assets/exact-home.js');
const css = read('assets/exact-home.css');
const worker = read('service-worker.js');
new vm.Script(js, { filename: 'assets/exact-home.js' });
assert(html.includes('assets/exact-home.css?v=3'));
assert(html.includes('assets/exact-home.js?v=3'));
assert(worker.includes('mohw-social-support-exact-home-v3'));
assert(worker.includes('assets/exact-home.css'));
assert(worker.includes('assets/exact-home.js'));
assert(js.includes('VIEW_W = 1448, VIEW_H = 1086'), 'Must use verified image dimensions');
assert(js.includes('assets/mohw-homepage-exact.png'));
assert(js.includes('assets/gia-introduction.mp4'));
assert(js.includes('position(desktopFrame, 151, 444, 492, 257)'), 'Video matches original image player frame');
assert(js.includes('desktopQuery = window.matchMedia'), 'Responsive breakpoint should be controlled');
assert(js.includes('const mobile = el(\'section\', \'exact-mobile\')'), 'Mobile premium view must exist');
assert(js.includes('state.artworkReady'), 'Safe fallback when art missing');
assert(js.includes("!document.documentElement.classList.contains('p2-contrast')"), 'High contrast remains accessible');
for (const kind of ["'nav'", "'gia'", "'access'", "'search'", "'share'", "'report'", "'message'", "'contact'"])
  assert(js.includes(kind), `Missing action ${kind}`);
assert(js.includes('video.play()'), 'Video must be playable');
assert(css.includes('object-fit:contain'), 'Artwork should not distort');
assert(css.includes('filter:blur'), 'Widescreen side panels should be filled');
assert(css.includes('@media(max-width:899px)'), 'Mobile presentation required');
assert(css.includes(':focus-visible'), 'Keyboard accessibility required');
assert(css.includes('#view-about .exact-player {position:absolute;z-index:6;isolation:isolate;overflow:hidden;border-radius:19px;pointer-events:none;border:0;box-shadow:none;background:transparent}'), 'A transparent frame must preserve original Gia poster');
assert(css.includes('.exact-video.exact-video-pending'), 'Video stays invisible until playing');
assert(js.includes("video.addEventListener('playing'"), 'Player should reveal only when playback begins');
assert(js.includes("button.setAttribute('aria-busy', 'true')"), 'Buffering button prevents duplicate actions');
console.log('Exact premium homepage: desktop, mobile, Gia poster visibility, video playback and navigation checks passed');
