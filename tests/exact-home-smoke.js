#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const read = p => fs.readFileSync(p, 'utf8');
const html = read('index.html');
const js = read('assets/exact-home.js');
const css = read('assets/exact-home.css');
const worker = read('service-worker.js');
new vm.Script(js, { filename: 'assets/exact-home.js' });
assert(html.includes('assets/exact-home.css?v=6-fluid'));
assert(html.includes('assets/exact-home.js?v=6-bottom-actions'));
assert(worker.includes('mohw-social-support-accessibility-v24'));
assert(worker.includes('assets/exact-home.css'));
assert(worker.includes('assets/exact-home.js'));
assert(js.includes('VIEW_W = 1448, VIEW_H = 1086'), 'Must use verified image dimensions');
assert(js.includes('assets/mohw-homepage-exact.png'));
assert(js.includes('assets/gia-introduction.mp4'));
assert(js.includes('position(desktopFrame, 151, 444, 492, 257)'), 'Video matches original image player frame');
assert(js.includes('desktopQuery = window.matchMedia'), 'Responsive breakpoint should be controlled');
assert(js.includes('const mobile = el(\'section\', \'exact-mobile\')'), 'Mobile premium view must exist');
assert(js.includes('state.artworkReady'), 'Safe fallback when art missing');
assert(js.includes("!document.documentElement.classList.contains('p2-contrast')"), 'High contrast remains accessible');
for (const kind of ["'nav'", "'gia'", "'access'", "'search'", "'share'", "'report'", "'message'", "'contact'"])
  assert(js.includes(kind), `Missing action ${kind}`);
assert(js.includes('video.play()'), 'Video must be playable');
assert(css.includes('object-fit:contain'), 'Artwork should not distort');
assert(css.includes('filter:blur'), 'Widescreen side panels should be filled');
assert(css.includes('@media(max-width:899px)'), 'Mobile presentation required');
assert(css.includes(':focus-visible'), 'Keyboard accessibility required');
assert(css.includes('#view-about .exact-player {position:absolute;z-index:6;isolation:isolate;overflow:hidden;border-radius:19px;pointer-events:none;border:0;box-shadow:none;background:transparent}'), 'A transparent frame must preserve original Gia poster');
assert(css.includes('.exact-video.exact-video-pending'), 'Video stays invisible until playing');
assert(js.includes("video.addEventListener('playing'"), 'Player should reveal only when playback begins');
assert(js.includes("button.setAttribute('aria-busy', 'true')"), 'Buffering button prevents duplicate actions');
assert(js.includes('mobile.insertBefore(meet, nav)'), 'GIA introduction should be first beneath mobile header');
assert(js.includes('document.body.append(utilities)'), 'Floating tools should be independent of scroll container');
assert(js.includes("utilities.hidden = !(mode === 'mobile' && homepageActive)"), 'Floating tools should only be shown on mobile homepage');
assert(!js.includes('mobile.append(gia)'), 'Do not duplicate the existing GIA launcher');
assert(css.includes('html.exact-home-visible #gia2Launcher.gia2-launcher{display:flex!important'), 'Existing GIA launcher must be visible on mobile');
assert(css.includes('#exact-mobile-utilities[hidden]{display:none!important}'), 'Floating dock must respect hidden state');
assert(css.includes('grid-template-columns:1fr;max-width:calc(100% - 84px)'), 'Readable mobile service cards must avoid floating tools');
assert(js.includes("['Share', 'share', '', 'share'], ['Report', 'report', '', 'report']"), 'Share and Report icons included');
assert(js.includes("['Message', 'message', '', 'message'], ['Download', 'nav', 'manual', 'download']"), 'Message and Download icons included');
assert(!js.includes("['Contact', 'contact', '', '☎']"), 'Dock must have exactly four actions');
assert(js.includes('nativeNav.classList.add(\'premium-nav-upgraded\')'), 'Native header must receive six premium choices');
assert(js.includes("accessNav.id = 'premium-mobile-access'"), 'Access option must use native settings');
assert(js.includes("contactLink.textContent = 'Contact directory'"), 'Contact action remains reachable');
assert(css.includes('grid-template-columns:repeat(2,52px);grid-auto-rows:52px'), 'Floating buttons must use 2 by 2 circles');
assert(css.includes('#exact-mobile .em-nav-symbol svg'), 'Illustrated header uses matching premium icons');
assert(css.includes('.site-header #mainNav.nav .premium-nav-icon'), 'Native header uses matching premium icons');
const polish=read('assets/premium-ui-fix.css');
const tools=read('assets/guide-tools.js');
assert(html.includes('premium-ui-fix.css?v=1'), 'Premium correction must be loaded last');
assert(worker.includes('assets/premium-ui-fix.css'), 'Service worker must cache the correction');
assert(polish.includes('grid-template-columns:repeat(3,minmax(0,1fr))!important'), 'Mobile nav must have three equal columns');
assert(polish.includes('grid-column:auto!important'), 'Last-child full-row override must be cleared');
assert(polish.includes('button.find:not(.active)'), 'Old yellow Services selector must be reset');
assert(polish.includes('#guideActionDock.guide-action-dock'), 'Actual native four-button dock must be styled');
assert(polish.includes('html.exact-home-visible body #guideActionDock'), 'The native dock must be displayed on the home overlay');
assert(polish.includes('grid-template-columns:repeat(6,minmax(0,1fr))!important'), 'Desktop nav should show six premium actions');
assert(tools.includes('data-action="download"'), 'Fourth button must open manual download, not app install');
assert(tools.includes('data-action="feedback"'), 'Feedback must remain functional');

assert(html.includes('assets/home-dock-rebalance.css?v=2-fluid'),'Rebalanced home layout stylesheet loaded');
assert(js.includes('exact-bottom-actions'),'Desktop actions are real buttons in bottom bar');
console.log('Premium mobile navigation, four-action dock, preserved Gia, and desktop polish checks passed');
